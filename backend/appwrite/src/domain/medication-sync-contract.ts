export function parseMedication(value: unknown, path = '$'): Medication {
  const data = object(value, path);
  exactKeys(
    data,
    [
      'contractVersion',
      'id',
      'householdId',
      'name',
      'pillType',
      'instructions',
      'revision',
      'deletedAt',
      'updatedAt',
    ],
    path,
  );
  return {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    id: id(data.id, `${path}.id`),
    householdId: id(data.householdId, `${path}.householdId`),
    name: stringValue(data.name, `${path}.name`, 200),
    pillType: enumValue(data.pillType, ['pill', 'capsule', 'tablet'], `${path}.pillType`),
    instructions:
      data.instructions === null
        ? null
        : stringValue(data.instructions, `${path}.instructions`, 2000),
    revision: integer(data.revision, `${path}.revision`, 1),
    deletedAt: nullableTimestamp(data.deletedAt, `${path}.deletedAt`),
    updatedAt: utcTimestamp(data.updatedAt, `${path}.updatedAt`),
  };
}

