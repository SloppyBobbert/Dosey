export function parseMutation(value: unknown, path = '$'): Mutation {
  const data = object(value, path);
  exactKeys(
    data,
    [
      'contractVersion',
      'mutationId',
      'deviceId',
      'idempotencyKey',
      'entityType',
      'operation',
      'entityId',
      'baseRevision',
      'payload',
    ],
    path,
  );
  const base = {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    mutationId: id(data.mutationId, `${path}.mutationId`),
    deviceId: id(data.deviceId, `${path}.deviceId`),
    idempotencyKey: id(data.idempotencyKey, `${path}.idempotencyKey`),
    entityId: id(data.entityId, `${path}.entityId`),
  };
  const entityType = enumValue(
    data.entityType,
    ['medication', 'schedule', 'dose_event'],
    `${path}.entityType`,
  );
  const operation = enumValue(data.operation, ['upsert', 'delete', 'append'], `${path}.operation`);
  const baseRevision =
    data.baseRevision === null ? null : integer(data.baseRevision, `${path}.baseRevision`, 1);

  if (entityType === 'medication' && operation === 'upsert') {
    return {...base, entityType, operation, baseRevision, payload: parseMedicationPayload(data.payload, `${path}.payload`)};
  }
  if (entityType === 'schedule' && operation === 'upsert') {
    return {...base, entityType, operation, baseRevision, payload: parseSchedulePayload(data.payload, `${path}.payload`)};
  }
  if ((entityType === 'medication' || entityType === 'schedule') && operation === 'delete') {
    if (baseRevision === null) fail('BASE_REVISION_REQUIRED', `${path}.baseRevision`, 'Delete requires a positive base revision.');
    if (data.payload !== null) fail('INVALID_MUTATION_PAYLOAD', `${path}.payload`, 'Delete payload must be null.');
    return {...base, entityType, operation, baseRevision, payload: null};
  }
  if (entityType === 'dose_event' && operation === 'append') {
    if (baseRevision !== null) fail('INVALID_BASE_REVISION', `${path}.baseRevision`, 'Dose event append does not use a revision.');
    return {...base, entityType, operation, baseRevision: null, payload: parseDoseEventPayload(data.payload, `${path}.payload`)};
  }
  fail('INVALID_MUTATION_OPERATION', `${path}.operation`, 'Operation does not match entity type.');
}

export function parseConflict(value: unknown, path = '$'): Conflict {
  const data = object(value, path);
  exactKeys(
    data,
    [
      'contractVersion',
      'entityType',
      'entityId',
      'expectedRevision',
      'actualRevision',
      'authoritativeRecord',
    ],
    path,
  );
  const entityType = enumValue(data.entityType, ['medication', 'schedule'], `${path}.entityType`);
  const entityId = id(data.entityId, `${path}.entityId`);
  const authoritativeRecord =
    entityType === 'medication'
      ? parseMedication(data.authoritativeRecord, `${path}.authoritativeRecord`)
      : parseSchedule(data.authoritativeRecord, `${path}.authoritativeRecord`);
  if (authoritativeRecord.id !== entityId) {
    fail('ENTITY_ID_MISMATCH', `${path}.authoritativeRecord.id`, 'Authoritative record ID does not match conflict entity ID.');
  }
  const actualRevision = integer(data.actualRevision, `${path}.actualRevision`, 1);
  const expectedRevision = integer(data.expectedRevision, `${path}.expectedRevision`, 1);
  if (expectedRevision === actualRevision) {
    fail('INVALID_CONFLICT_REVISIONS', path, 'Conflict revisions must differ.');
  }
  if (authoritativeRecord.revision !== actualRevision) {
    fail('REVISION_MISMATCH', `${path}.authoritativeRecord.revision`, 'Authoritative revision does not match conflict revision.');
  }
  return {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    entityType,
    entityId,
    expectedRevision,
    actualRevision,
    authoritativeRecord,
  };
}

export function parseMutationAck(value: unknown, path = '$'): MutationAck {
  const data = object(value, path);
  exactKeys(
    data,
    ['contractVersion', 'mutationId', 'outcome', 'revision', 'cursor', 'errorCode', 'conflict'],
    path,
  );
  const outcome = enumValue(
    data.outcome,
    ['applied', 'duplicate', 'conflict', 'rejected'],
    `${path}.outcome`,
  );
  const revision = data.revision === null ? null : integer(data.revision, `${path}.revision`, 1);
  const cursor = nullableCursor(data.cursor, `${path}.cursor`);
  const errorCode = nullableString(data.errorCode, `${path}.errorCode`);
  const conflict = data.conflict === null ? null : parseConflict(data.conflict, `${path}.conflict`);
  if ((outcome === 'applied' || outcome === 'duplicate') && cursor === null) {
    fail('CURSOR_REQUIRED', `${path}.cursor`, 'Applied and duplicate acknowledgements require a cursor.');
  }
  if (outcome === 'conflict' && conflict === null) {
    fail('CONFLICT_REQUIRED', `${path}.conflict`, 'Conflict acknowledgement requires conflict details.');
  }
  if (outcome === 'rejected' && errorCode === null) {
    fail('ERROR_CODE_REQUIRED', `${path}.errorCode`, 'Rejected acknowledgement requires an error code.');
  }
  if (outcome !== 'conflict' && conflict !== null) {
    fail('UNEXPECTED_CONFLICT', `${path}.conflict`, 'Conflict details are only valid for conflict outcome.');
  }
  if ((outcome === 'applied' || outcome === 'duplicate') && errorCode !== null) {
    fail('UNEXPECTED_ERROR_CODE', `${path}.errorCode`, 'Successful acknowledgements cannot include an error code.');
  }
  if (outcome === 'conflict' && (revision !== null || cursor !== null || errorCode !== null)) {
    fail('CONTRADICTORY_ACK', path, 'Conflict acknowledgement cannot include revision, cursor, or error code.');
  }
  if (outcome === 'rejected' && (revision !== null || cursor !== null)) {
    fail('CONTRADICTORY_ACK', path, 'Rejected acknowledgement cannot include revision or cursor.');
  }
  return {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    mutationId: id(data.mutationId, `${path}.mutationId`),
    outcome,
    revision,
    cursor,
    errorCode,
    conflict,
  };
}

function parsePullChange(value: unknown, path: string): PullChange {
  const data = object(value, path);
  exactKeys(data, ['cursor', 'entityType', 'entityId', 'operation', 'record'], path);
  const entityType = enumValue(
    data.entityType,
    ['medication', 'schedule', 'dose_event'],
    `${path}.entityType`,
  );
  const entityId = id(data.entityId, `${path}.entityId`);
  const operation = enumValue(data.operation, ['upsert', 'delete', 'append'], `${path}.operation`);
  let record: Medication | Schedule | DoseEvent;
  if (entityType === 'medication' && (operation === 'upsert' || operation === 'delete')) {
    record = parseMedication(data.record, `${path}.record`);
  } else if (entityType === 'schedule' && (operation === 'upsert' || operation === 'delete')) {
    record = parseSchedule(data.record, `${path}.record`);
  } else if (entityType === 'dose_event' && operation === 'append') {
    record = parseDoseEvent(data.record, `${path}.record`);
  } else {
    fail('INVALID_CHANGE_OPERATION', `${path}.operation`, 'Operation does not match entity type.');
  }
  if (record.id !== entityId) {
    fail('ENTITY_ID_MISMATCH', `${path}.record.id`, 'Record ID does not match change entity ID.');
  }
  if (operation === 'delete' && 'deletedAt' in record && record.deletedAt === null) {
    fail('TOMBSTONE_REQUIRED', `${path}.record.deletedAt`, 'Delete change requires a tombstone.');
  }
  return {
    cursor: cursor(data.cursor, `${path}.cursor`),
    entityType,
    entityId,
    operation,
    record,
  };
}

export function parsePullPage(value: unknown, path = '$'): PullPage {
  const data = object(value, path);
  exactKeys(
    data,
    ['contractVersion', 'robotId', 'cursor', 'checkpoint', 'nextCursor', 'hasMore', 'changes'],
    path,
  );
  if (!Array.isArray(data.changes)) fail('INVALID_TYPE', `${path}.changes`, 'Expected an array.');
  const robotId = id(data.robotId, `${path}.robotId`);
  const changes = data.changes.map((change, index) =>
    parsePullChange(change, `${path}.changes[${index}]`),
  );
  const pageCursor = nullableCursor(data.cursor, `${path}.cursor`);
  const checkpoint = cursor(data.checkpoint, `${path}.checkpoint`);
  const nextCursor = cursor(data.nextCursor, `${path}.nextCursor`);
  const pageCursorNumber = pageCursor === null ? -1 : Number(pageCursor);
  const checkpointNumber = Number(checkpoint);
  const nextCursorNumber = Number(nextCursor);
  if (pageCursorNumber > nextCursorNumber || nextCursorNumber > checkpointNumber) {
    fail('INVALID_CURSOR_ORDER', path, 'Expected cursor <= nextCursor <= checkpoint.');
  }
  let priorChangeCursor = pageCursorNumber;
  for (const [index, change] of changes.entries()) {
    if (change.record.householdId !== robotId) {
      fail(
        'ROBOT_SCOPE_MISMATCH',
        `${path}.changes[${index}].record.householdId`,
        'Pull record does not belong to the page robot scope.',
      );
    }
    const changeCursor = Number(change.cursor);
    if (changeCursor <= priorChangeCursor || changeCursor > nextCursorNumber) {
      fail(
        'INVALID_CURSOR_ORDER',
        `${path}.changes[${index}].cursor`,
        'Change cursors must increase and not exceed nextCursor.',
      );
    }
    priorChangeCursor = changeCursor;
  }
  const hasMore = booleanValue(data.hasMore, `${path}.hasMore`);
  if (hasMore) {
    if (nextCursorNumber >= checkpointNumber) {
      fail('INVALID_HAS_MORE', `${path}.hasMore`, 'hasMore requires nextCursor before checkpoint.');
    }
    if (nextCursorNumber <= pageCursorNumber) {
      fail('PULL_PAGE_NO_PROGRESS', `${path}.nextCursor`, 'A nonterminal page must advance its cursor.');
    }
  } else if (nextCursorNumber !== checkpointNumber) {
    fail('INCOMPLETE_PULL_PAGE', `${path}.nextCursor`, 'A terminal page must reach its checkpoint.');
  }
  return {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    robotId,
    cursor: pageCursor,
    checkpoint,
    nextCursor,
    hasMore,
    changes,
  };
}

export function parsePushRequest(value: unknown, path = '$'): PushRequest {
  const data = object(value, path);
  exactKeys(data, ['contractVersion', 'robotId', 'operations'], path);
  if (!Array.isArray(data.operations)) fail('INVALID_TYPE', `${path}.operations`, 'Expected an array.');
  if (data.operations.length > 100) fail('BATCH_TOO_LARGE', `${path}.operations`, 'At most 100 operations are allowed.');
  return {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    robotId: id(data.robotId, `${path}.robotId`),
    operations: data.operations.map((operation, index) =>
      parseMutation(operation, `${path}.operations[${index}]`),
    ),
  };
}

export function parsePushResponse(value: unknown, path = '$'): PushResponse {
  const data = object(value, path);
  exactKeys(data, ['contractVersion', 'robotId', 'acknowledgements'], path);
  if (!Array.isArray(data.acknowledgements)) {
    fail('INVALID_TYPE', `${path}.acknowledgements`, 'Expected an array.');
  }
  const robotId = id(data.robotId, `${path}.robotId`);
  const acknowledgements = data.acknowledgements.map((ack, index) =>
    parseMutationAck(ack, `${path}.acknowledgements[${index}]`),
  );
  for (const [index, acknowledgement] of acknowledgements.entries()) {
    if (
      acknowledgement.conflict !== null &&
      acknowledgement.conflict.authoritativeRecord.householdId !== robotId
    ) {
      fail(
        'ROBOT_SCOPE_MISMATCH',
        `${path}.acknowledgements[${index}].conflict.authoritativeRecord.householdId`,
        'Conflict record does not belong to the response robot scope.',
      );
    }
  }
  return {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    robotId,
    acknowledgements,
  };
}

export function parsePullRequest(value: unknown, path = '$'): PullRequest {
  const data = object(value, path);
  exactKeys(data, ['contractVersion', 'robotId', 'cursor', 'checkpoint', 'limit'], path);
  const cursor = nullableCursor(data.cursor, `${path}.cursor`);
  const checkpoint = nullableCursor(data.checkpoint, `${path}.checkpoint`);
  if ((cursor === null) !== (checkpoint === null)) {
    fail(
      'INVALID_PAGINATION_STATE',
      path,
      'Cursor and checkpoint must either both be null or both be present.',
    );
  }
  if (cursor !== null && checkpoint !== null && Number(cursor) > Number(checkpoint)) {
    fail('INVALID_CURSOR_ORDER', path, 'Cursor cannot exceed checkpoint.');
  }
  return {
    contractVersion: version(data.contractVersion, `${path}.contractVersion`),
    robotId: id(data.robotId, `${path}.robotId`),
    cursor,
    checkpoint,
    limit: integer(data.limit, `${path}.limit`, 1, 100),
  };
}

export function parseMedicationSyncValue(type: string, value: unknown): unknown {
  switch (type) {
    case 'householdRole':
      return parseHouseholdRole(value);
    case 'medication':
      return parseMedication(value);
    case 'schedule':
      return parseSchedule(value);
    case 'occurrenceRef':
      return parseOccurrenceRef(value);
    case 'doseEvent':
      return parseDoseEvent(value);
    case 'mutation':
      return parseMutation(value);
    case 'ack':
      return parseMutationAck(value);
    case 'conflict':
      return parseConflict(value);
    case 'pullPage':
      return parsePullPage(value);
    case 'pushRequest':
      return parsePushRequest(value);
    case 'pushResponse':
      return parsePushResponse(value);
    case 'pullRequest':
      return parsePullRequest(value);
    default:
      fail('UNKNOWN_FIXTURE_TYPE', '$.type', `Unknown fixture type: ${type}.`);
  }
}

export function canonicalMedicationSyncJson(value: unknown): string {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) {
    return `[${value.map(canonicalMedicationSyncJson).join(',')}]`;
  }
  const entries = Object.entries(value as JsonObject).sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  );
  return `{${entries.map(([key, entry]) => `${JSON.stringify(key)}:${canonicalMedicationSyncJson(entry)}`).join(',')}}`;
}

export function canonicalMutationHashInput(robotId: string, value: unknown): string {
  return canonicalMedicationSyncJson({
    robotId: id(robotId, '$.robotId'),
    mutation: parseMutation(value, '$.mutation'),
  });
}

export function assertMatchingIdempotentReplay(
  originalRobotId: string,
  original: Mutation,
  replayRobotId: string,
  replay: Mutation,
): void {
  const originalScope = id(originalRobotId, '$.originalRobotId');
  const replayScope = id(replayRobotId, '$.replayRobotId');
  if (originalScope !== replayScope) {
    fail(
      'IDEMPOTENCY_SCOPE_MISMATCH',
      '$.robotId',
      'Mutations belong to different robot idempotency scopes.',
    );
  }
  if (original.idempotencyKey !== replay.idempotencyKey) {
    fail('IDEMPOTENCY_KEY_MISMATCH', '$.idempotencyKey', 'Mutations use different idempotency keys.');
  }
  if (
    canonicalMutationHashInput(originalScope, original) !==
    canonicalMutationHashInput(replayScope, replay)
  ) {
    fail(
      'IDEMPOTENCY_KEY_REUSED',
      '$.idempotencyKey',
      'Idempotency key was reused with a changed mutation.',
    );
  }
}
